<?php

declare(strict_types=1);

namespace Kaly\Core;

use Kaly\Ex;
use Kaly\Util\Fs;
use Psr\Http\Message\ServerRequestFactoryInterface;

/**
 * The files an application actually loads, written as an `opcache.preload`
 * script.
 *
 * Recording boots the application and handles a few GET requests, then lists
 * every file the PHP process included: run it in a dedicated CLI process, so
 * nothing else is recorded. The script only compiles these files, it never
 * executes them: a file that depends on the bootstrap (a `class_alias()`, a
 * constant, a conditional declaration) cannot fail the pool startup. Opcache
 * links classes once every file is compiled; a class it cannot link is logged
 * at startup and loaded at runtime as usual. Record after
 * `composer install --no-dev`, in the tree that is deployed, and generate again
 * on each deploy.
 */
final class Preload
{
    /**
     * @param list<string> $files
     */
    private function __construct(
        private readonly array $files,
    ) {}

    /**
     * Boot the application (unless booted), handle each path as a GET request,
     * then capture what the process included. A path answering 4xx or 5xx
     * fails the recording rather than silently preloading less. Choose paths
     * without side effects: they run like real requests. Without paths, the
     * boot alone is recorded.
     *
     * @param list<string> $paths
     */
    public static function record(App $app, array $paths = []): self
    {
        if (!$app->isBooted()) {
            $app->boot();
        }
        $factory = $app->container()->get(ServerRequestFactoryInterface::class);
        foreach ($paths as $path) {
            $status = $app->handle($factory->createServerRequest('GET', $path))->getStatusCode();
            if ($status >= 400) {
                throw new Ex("Preload path {$path} answered {$status}");
            }
        }

        // The entry script records, it is never part of the application
        return new self(array_slice(get_included_files(), 1));
    }

    /**
     * The recorded files, in inclusion order.
     *
     * @return list<string>
     */
    public function files(): array
    {
        return $this->files;
    }

    /**
     * The preload script for this location: files below its directory are
     * written relative to it, so the tree can be built in one place and
     * served from another.
     */
    public function script(string $file): string
    {
        // Recorded files are real paths: compare them with the real directory
        $dir = realpath(dirname($file)) ?: dirname($file);
        $files = '';
        foreach ($this->files as $source) {
            $relative = Fs::relativePath($dir, $source);
            $files .=
                '    ' . ($relative === $source ? var_export($source, true) : '__DIR__ . ' . var_export('/' . $relative, true)) . ",\n";
        }

        return <<<PHP
            <?php

            // Generated by Kaly\\Core\\Preload for one release: regenerate it on
            // each deploy, then reload PHP-FPM so opcache.preload runs it again.
            // It compiles files without executing them; never require
            // vendor/autoload.php here, it would run the Composer `files` entries
            // that every request runs again.

            \$files = [
            {$files}];

            foreach (\$files as \$file) {
                if (is_file(\$file)) {
                    opcache_compile_file(\$file);
                }
            }

            PHP;
    }

    /**
     * Write the script atomically: a pool starting meanwhile reads the previous
     * script or the new one, never a partial file.
     */
    public function write(string $file): void
    {
        $tmp = Fs::join(dirname($file), '.' . basename($file) . '.' . getmypid() . '.tmp');
        if (!Fs::putFile($tmp, $this->script($file)) || !@rename($tmp, $file)) {
            @unlink($tmp);
            throw new Ex("Cannot write the preload script to {$file}");
        }
    }
}
