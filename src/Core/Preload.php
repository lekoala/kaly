<?php

declare(strict_types=1);

namespace Kaly\Core;

use Kaly\Ex;
use Kaly\Util\Fs;
use Psr\Http\Message\ServerRequestFactoryInterface;
use ReflectionClass;

/**
 * The files an application actually loads, written as an `opcache.preload`
 * script.
 *
 * Recording boots the application and handles a few GET requests in the
 * current process, then lists the files PHP loaded. The script only compiles
 * them, it never executes them: a file that depends on the bootstrap (a
 * `class_alias()`, a constant, a conditional declaration) cannot fail the
 * pool startup. Class files come first, in an order where every parent,
 * interface and trait precedes the classes using it, so opcache can link
 * them; a class it cannot link is logged at startup and loaded at runtime as
 * usual. Record after `composer install --no-dev`, in the tree that is
 * deployed, and generate again on each deploy.
 */
final class Preload
{
    /**
     * @param list<string> $files
     */
    private function __construct(
        private readonly array $files,
    ) {}

    /**
     * Boot the application (unless booted), handle each path as a GET request
     * whatever its response, then capture what the process loaded. Choose
     * paths without side effects: they run like real requests.
     *
     * @param list<string> $paths
     */
    public static function record(App $app, array $paths = []): self
    {
        if (!$app->isBooted()) {
            $app->boot();
        }
        $factory = $app->container()->get(ServerRequestFactoryInterface::class);
        foreach ($paths as $path) {
            $app->handle($factory->createServerRequest('GET', $path));
        }

        // The entry script records, it is never part of the application
        $entry = get_included_files()[0] ?? null;
        // Each list is in declaration order, and interfaces only extend
        // interfaces, traits only use traits: dependencies always come first
        $files = [];
        foreach ([...get_declared_interfaces(), ...get_declared_traits(), ...get_declared_classes()] as $class) {
            $reflection = new ReflectionClass($class);
            $file = $reflection->getFileName();
            // Aliases resolve to their target, anonymous classes are declared
            // by the code that uses them
            if ($file === false || $reflection->getName() !== $class || $reflection->isAnonymous()) {
                continue;
            }
            $files[$file] = true;
        }
        // Then the files declaring no class (module config.php, ...)
        foreach (get_included_files() as $file) {
            $files[$file] = true;
        }
        if ($entry !== null) {
            unset($files[$entry]);
        }

        return new self(array_keys($files));
    }

    /**
     * The recorded files, in compilation order.
     *
     * @return list<string>
     */
    public function files(): array
    {
        return $this->files;
    }

    /**
     * The preload script for this location: files below its directory are
     * written relative to it, so the tree can be built in one place and
     * served from another.
     */
    public function script(string $file): string
    {
        // Recorded files are real paths: compare them with the real directory
        $dir = realpath(dirname($file)) ?: dirname($file);
        $files = '';
        foreach ($this->files as $source) {
            $relative = Fs::relativePath($dir, $source);
            $files .=
                '    ' . ($relative === $source ? var_export($source, true) : '__DIR__ . ' . var_export('/' . $relative, true)) . ",\n";
        }

        return <<<PHP
            <?php

            // Generated by Kaly\\Core\\Preload for one release: regenerate it on
            // each deploy, then restart PHP-FPM so opcache.preload runs it again.
            // It compiles files without executing them; never require
            // vendor/autoload.php here, it would run the Composer `files` entries
            // that every request runs again.

            \$files = [
            {$files}];

            foreach (\$files as \$file) {
                if (is_file(\$file)) {
                    opcache_compile_file(\$file);
                }
            }

            PHP;
    }

    public function write(string $file): void
    {
        if (!Fs::putFile($file, $this->script($file))) {
            throw new Ex("Cannot write the preload script to {$file}");
        }
    }
}
